class L10nDelegate extends LocalizationsDelegate<L10n> {
  const L10nDelegate(this.code);
  final String code;

  @override
  bool isSupported(Locale locale) => true;

  @override
  Future<L10n> load(Locale locale) async => L10n.forCode(code);

  @override
  bool shouldReload(L10nDelegate old) => old.code != code;
}
